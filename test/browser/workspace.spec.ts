import { randomBytes } from 'node:crypto';
import { expect, test } from '@playwright/test';

test('onboard, manage student records, switch theme and use mobile navigation', async ({ page }) => {
  const uncaught: string[] = [];
  page.on('pageerror', (error) => uncaught.push(error.message));
  const suffix = randomBytes(4).toString('hex');
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Welcome back' })).toBeVisible();
  await page.getByRole('button', { name: 'Create a workspace' }).click();
  await page.getByLabel('Institution name').fill('Lusaka Demo ' + suffix);
  await page.getByLabel('Full name').fill('Chanda Administrator');
  await page.getByLabel('Email address').fill('eli-' + suffix + '@example.test');
  await page.getByLabel('Password').fill('A long browser test passphrase');
  await page.getByRole('button', { name: 'Create workspace', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Welcome back, Chanda.' })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Attendance overview' })).toBeVisible();
  await page.getByRole('button', { name: 'Add student', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog).toBeVisible();
  await dialog.getByLabel('Full name').fill('Memory Banda');
  await expect(dialog.getByLabel('Student number')).toHaveValue('');
  await expect(dialog.getByText('Leave blank to generate a number', { exact: false })).toBeVisible();
  await dialog.getByRole('button', { name: 'Save record' }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Memory Banda', exact: true })).toBeVisible();
  await expect(page.getByRole('cell', { name: /^STU-\d{10}$/ })).toBeVisible();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export CSV' }).click();
  expect((await download).suggestedFilename()).toBe('students.csv');
  await page.reload();
  await page.getByRole('button', { name: 'Memory Banda', exact: true }).click();
  await expect(dialog.getByText(/^STU-\d{10}$/)).toBeVisible();
  await dialog.getByRole('button', { name: 'Edit', exact: true }).click();
  await dialog.getByLabel('Student number').fill('2026-011');
  await dialog.getByRole('button', { name: 'Save record' }).click();
  await page.getByRole('button', { name: 'Memory Banda', exact: true }).click();
  await expect(dialog.getByText('2026-011')).toBeVisible();
  await dialog.getByRole('button', { name: 'Close dialog' }).click();
  await page.getByRole('button', { name: 'Switch to dark mode' }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await page.getByRole('navigation').getByRole('link', { name: 'Overview', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Overview', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.getByRole('button', { name: 'Account menu' }).click();
  await page.getByRole('button', { name: 'Sign out' }).click();
  await expect(page.getByRole('heading', { name: 'Welcome back', exact: true })).toBeVisible();
  expect(uncaught).toEqual([]);
});
